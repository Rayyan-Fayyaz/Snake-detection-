package com.finaltime.catalogue_management.entity;

public enum DangerLevel {
    NONE,       // not dangerous (non-venomous)
    LOW,        // venomous but bite rarely serious
    MODERATE,   // can cause serious symptoms, medical attention needed
    HIGH,       // life-threatening without treatment
    EXTREME     // among the most dangerous, rapid onset, high fatality risk untreated
}
